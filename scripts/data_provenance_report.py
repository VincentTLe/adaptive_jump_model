def span(path: Path) -> tuple:
    """First date, last date, row count and hash, for any of our input shapes.

    The raw files disagree about almost everything: French's factors carry three
    lines of preamble and 8-digit integer dates, the ECB export is 40 columns
    wide, and the FRED downloads name their date column three different ways.
    Rather than special-case each, read leniently and pick whichever column
    parses as dates for most of its rows.
    """
    digest = hashlib.sha256(path.read_bytes()).hexdigest()
    frame = None
    for skiprows in (0, 1, 2, 3, 4):
        try:
            # low_memory belongs to the C parser only; passing it here raises.
            candidate = pd.read_csv(path, skiprows=skiprows, engine="python",
                                    on_bad_lines="skip")
        except (pd.errors.ParserError, ValueError):
            continue
        if len(candidate.columns) >= 2 and len(candidate):
            frame = candidate
            break
    if frame is None:
        return pd.NaT, pd.NaT, 0, digest

    best, best_dates = None, None
    for column in frame.columns:
        raw = frame[column].astype(str).str.strip()
        # French stamps dates as 19260701; everything else is ISO-like.
        parsed = (pd.to_datetime(raw, format="%Y%m%d", errors="coerce")
                  if raw.str.fullmatch(r"\d{8}").mean() > 0.5
                  else pd.to_datetime(raw, errors="coerce", format="mixed"))
        share = parsed.notna().mean()
        if share > 0.5 and (best is None or share > best):
            best, best_dates = share, parsed.dropna()
    if best_dates is None or best_dates.empty:
        return pd.NaT, pd.NaT, len(frame), digest
    return best_dates.min(), best_dates.max(), len(frame), digest


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    config = load_config(CONFIG)

    rows = []
    for market in config.markets:
        for kind, source in (("equity", market.equity), ("cash", market.cash)):
            path_text = source.settings.get("file_path")
            observed = source.settings.get("source_start_observed")
            if path_text:
                path = ROOT / path_text
                first, last, count, digest = span(path)
                pinned = source.settings.get("sha256", "")
                ok = digest == pinned
            else:
                first = pd.Timestamp(observed) if observed else pd.NaT
                last, count, ok = pd.NaT, None, None
                path_text = f"(fetched live: {source.settings.get('retrieval_url', '')})"
            rows.append({
                "market": market.id, "leg": kind, "source_id": source.source_id,
                "provider": source.provider,
                "canonical_url": source.settings.get("canonical_url", ""),
                "file": path_text,
                "first": first, "last": last, "rows": count,
                "declared_start": observed,
                "sha256_matches_config": ok,
            })
    canonical = pd.DataFrame(rows)
    canonical.to_csv(OUT / "canonical-series.csv", index=False,
                     lineterminator="\n")

    inputs = []
    for name, (description, url) in sorted(INPUT_SOURCES.items()):
        path = ROOT / "data" / "external" / "inputs" / name
        if not path.is_file():
            inputs.append({"file": name, "description": description, "url": url,
                           "first": pd.NaT, "last": pd.NaT, "rows": 0,
                           "sha256": "MISSING"})
            continue
        first, last, count, digest = span(path)
        inputs.append({"file": name, "description": description, "url": url,
                       "first": first, "last": last, "rows": count,
                       "sha256": digest})
    input_frame = pd.DataFrame(inputs)
    input_frame.to_csv(OUT / "raw-inputs.csv", index=False, lineterminator="\n")

    lines = ["NGUỒN DỮ LIỆU — chuỗi chuẩn hoá dùng trong hợp đồng "
             f"{config.config_id}", ""]
    for r in canonical.itertuples():
        head = f"  {r.market} {r.leg:<7} {r.source_id}"
        lines.append(head)
        lines.append(f"      nguồn : {r.canonical_url}")
        lines.append(f"      file  : {r.file}")
        if pd.notna(r.last):
            lines.append(f"      phủ   : {r.first.date()} .. {r.last.date()}"
                         f"  ({r.rows} dòng)"
                         f"   hash khớp config: "
                         f"{'có' if r.sha256_matches_config else 'KHÔNG'}")
        else:
            lines.append(f"      phủ   : từ {r.declared_start} (tải trực tiếp)")
        lines.append("")

    lines.append("ĐỦ SỚM CHƯA? Paper nói dữ liệu bắt đầu 1970, nhưng quy trình")
    lines.append("cần 3000 phiên huấn luyện + 8 năm kiểm định TRƯỚC ngày ngoài")
    lines.append("mẫu đầu tiên, nên chuỗi phải bắt đầu sớm hơn 1990 khoảng 20")
    lines.append("năm. Thiếu ở đầu chuỗi thì không mất phần đầu dữ liệu — mà")
    lines.append("mất phần đầu của chính giai đoạn báo cáo 1990-2023.")
    lines.append("")
    lines.append(f"  {'chuỗi':<22}{'bắt đầu':>12}{'so với 1970':>14}"
                 f"{'so với mốc cần':>17}")
    need = OOS_START - pd.DateOffset(years=VALIDATION_YEARS) \
        - pd.DateOffset(days=int(FIT_WINDOW_DAYS * 365.25 / 252))
    for r in canonical.itertuples():
        if pd.isna(r.first):
            continue
        d70 = (PAPER_START - r.first).days / 365.25
        dneed = (need - r.first).days / 365.25
        lines.append(f"  {r.market + ' ' + r.leg:<22}{str(r.first.date()):>12}"
                     f"{d70:>+13.1f}n{dneed:>+16.1f}n")
    lines.append(f"\n  mốc cần thiết ~ {need.date()} "
                 f"(= {OOS_START.date()} lùi 8 năm kiểm định "
                 f"và {FIT_WINDOW_DAYS} phiên huấn luyện)")
    lines.append("  số dương = chuỗi bắt đầu SỚM hơn mốc, tức là đủ.")

    lines.append("\n\nDỮ LIỆU THÔ ĐƯỢC GHIM HASH (nguyên liệu để dựng các chuỗi trên)")
    lines.append("")
    for r in input_frame.itertuples():
        lines.append(f"  {r.file}")
        lines.append(f"      {r.description}")
        lines.append(f"      {r.url}")
        if pd.notna(r.first):
            lines.append(f"      {r.first.date()} .. {r.last.date()}"
                         f"  ({r.rows} dòng)  sha256 {r.sha256[:16]}…")
        lines.append("")

    report = "\n".join(lines) + "\n"
    (OUT / "report.txt").write_text(report, encoding="utf-8")
    print(report)
    print(f"đã ghi {OUT.relative_to(ROOT)}/")


if __name__ == "__main__":
    main()

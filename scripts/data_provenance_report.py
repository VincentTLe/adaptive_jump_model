"""Every series we use: where it came from, what it spans, and whether it reaches.

Written because the question "is our data good enough?" only has an answer
relative to what the paper needs, and what the paper needs is not the 1970 it
states. Section 3.4.3 requires a 3000-day training window and then an 8-year
validation window before the first out-of-sample day, so a series starting at
1970-01-01 puts the first tradeable day near 1990 -- which is the point. A
series that starts late does not shorten the sample at one end; it deletes the
front of the reported 1990-2023 period.

Prints one row per series with its true observed span, the sha256 that the
frozen config pins, and how much slack it has against the paper's requirement.
Writes the same to artifacts/data-provenance/ so it can be attached to an email
without being regenerated by hand.
"""


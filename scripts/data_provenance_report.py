PAPER_END = pd.Timestamp("2023-12-31")
FIT_WINDOW_DAYS = 3000          # trading days, Section 3.4.2
VALIDATION_YEARS = 8            # Section 3.4.3
OOS_START = pd.Timestamp("1990-01-02")

